export const STONE_VARIANT_COUNT = stoneCatalog.length;
export const STONE_SHAPE_COUNT = 112;

// Stable catalog indexes are intentionally kept for saved user data. The first
// 128 keep their original 64 silhouettes. Later catalog waves receive their own
// silhouette ranges so newly discovered friends are visibly different.
export function stoneShapeIndex(stoneIndex: number) {
  if (stoneIndex < 128) {
    return (Math.imul(stoneIndex, 17) + Math.floor(stoneIndex / 96) * 7) % 64;
  }
  if (stoneIndex < 160) {
    return 64 + (Math.imul(stoneIndex - 128, 5) % 16);
  }
  return 80 + (Math.imul(stoneIndex - 160, 13) % (STONE_SHAPE_COUNT - 80));
}

export const stoneCatalogEntries = stoneCatalog
  .map(([name, goal], index) => ({ name, goal, index }))
  .sort((left, right) => left.goal - right.goal || left.index - right.index);

export function unlockedStoneEntries(total: number) {
  return stoneCatalogEntries.filter((entry) => entry.goal <= total);
}

export function unlockedStones(total: number) {
  return unlockedStoneEntries(total).map(({ name, goal }) => [name, goal] as const);
}

export function unlockedStoneIndex(recordKey: string, total: number) {
  const unlocked = unlockedStoneEntries(total);
  if (!unlocked.length) return null;
  let hash = 2166136261;
  for (const character of recordKey) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return unlocked[(hash >>> 0) % unlocked.length].index;
}

export function stoneSpeciesIndexes(total: number, count: number, offset = 0) {
  const unlockedIndexes = unlockedStoneEntries(total).map((entry) => entry.index);
  if (unlockedIndexes.length === 0 || count <= 0) return [];

  const result: number[] = [];
  let seed = Math.imul(total + 17, 2654435761) ^ Math.imul(offset + 31, 1597334677);
  while (result.length < count) {
    const deck = [...unlockedIndexes];
    for (let index = deck.length - 1; index > 0; index -= 1) {
      seed = Math.imul(seed ^ (seed >>> 16), 2246822507) + 3266489909;
      const swapIndex = (seed >>> 0) % (index + 1);
      [deck[index], deck[swapIndex]] = [deck[swapIndex], deck[index]];
    }
    if (deck.length > 1 && result.at(-1) === deck[0]) {
      [deck[0], deck[1]] = [deck[1], deck[0]];
    }
    result.push(...deck.slice(0, count - result.length));
    seed += 1013904223;
  }
  return result;
}
